class Builder:
    def __init__(self, tools: Tools, force: bool, demo: dict):
        self.t = tools
        self.force = force
        self.demo = demo
        self.generated: dict[tuple, Path] = {}
        self.base_week: dict | None = None
        self.bundles: dict[str, str] = {}  # "scenario/run" -> bundle path relative to OUT

    # ---- instances

    def generated_instance(self, spec: dict) -> Path:
        cfg = spec["config"]
        seed = int(spec["seed"])
        key = (cfg, seed, bool(spec.get("no_certify", False)))
        if key in self.generated:
            return self.generated[key]
        d = DATA / "gen" / f"{Path(cfg).stem}_{seed}"
        if self.force or not (d / "week.json").exists():
            if d.exists():
                shutil.rmtree(d)
            args = ["--config", ROOT / cfg, "--seed", seed, "--out", d]
            if spec.get("no_certify"):
                args.append("--no-certify")
            self.t.run("generate", *args)
        self.generated[key] = d
        return d

    def base(self) -> dict:
        if self.base_week is None:
            self.base_week = read_json(self.generated_instance({"config": "config/instance_small.yaml", "seed": 1}) / "week.json")
        return self.base_week

    def instance(self, sid: str, key: str, spec: dict, done: dict[str, Path]) -> Path:
        if "generate" in spec:
            return self.generated_instance(spec["generate"])
        d = DATA / sid / key
        if "hand" in spec:
            w, m = HAND_INSTANCES[spec["hand"]](self.base())
        elif "from" in spec:
            src = done[spec["from"]]
            w, m = read_json(src / "week.json"), read_json(src / "matrix.json")
            w["name"] = f"{w['name']}_{key}"
        else:
            raise SystemExit(f"{sid}: instance {key} needs generate, hand or from")
        for k, v in spec.get("rules", {}).items():
            if k not in w["rules"]:
                raise SystemExit(f"{sid}: unknown rule {k}")
            w["rules"][k] = v
        if d.exists():
            shutil.rmtree(d)
        write_json(d / "week.json", w, indent=2)
        write_json(d / "matrix.json", m, indent=2)
        if "from" in spec and (done[spec["from"]] / "truth.json").exists():
            shutil.copy(done[spec["from"]] / "truth.json", d / "truth.json")
        return d

    # ---- runs

    def estimator(self, config: str) -> Path:
        f = ROOT / "results" / "estimators" / f"{Path(config).stem}.json"
        if self.force or not f.exists():
            self.t.run("learn", "--config", ROOT / config)
        return f

    def run(self, sid: str, run: dict, inst: Path, inst_spec: dict) -> dict:
        rid = run["id"]
        entry = {"id": rid, "label": run.get("label", rid), "note": run.get("note", ""), "solver": run.get("solver", "hand")}
        if "ref" in run:
            if run["ref"] not in self.bundles:
                raise SystemExit(f"{sid}/{rid}: {run['ref']} is not built (order of scenarios)")
            entry["file"] = self.bundles[run["ref"]]
            self.bundles[f"{sid}/{rid}"] = entry["file"]
            return entry
        if run.get("requires_gurobi") and not self.t.gurobi:
            entry["unavailable"] = "nécessite Gurobi (binaire construit sans Gurobi)"
            return entry
        rel = f"{sid}/{rid}.json"
        out = OUT / rel
        name = f"demo_{sid}_{rid}"
        if "plan" in run:  # hand-made plan, exported as it is (illegal plans included)
            w, m = read_json(inst / "week.json"), read_json(inst / "matrix.json")
            plans = DATA / sid / "plans" / rid
            p = hand_plan(w, m, run["plan"]["sequence"], [tuple(b) for b in run["plan"].get("breaks", [])])
            write_json(plans / "day0" / "plan.json", p, indent=2)
            self.t.run("export", "--instance", inst, "--plans", plans, "--out", out, "--run", name,
                       "--solver", "hand", ok=(0, 1))
        else:
            args = ["--instance", inst, "--solver", run["solver"], "--run", name, "--bundle", out]
            if run["solver"] == "alns":
                args += ["--iterations", run.get("iterations", self.demo.get("alns_iterations", 20000))]
            if "time_limit" in run:
                args += ["--time-limit", run["time_limit"]]
            if "profile" in run:
                args += ["--profile", run["profile"]]
            if "fairness" in run:
                args += ["--fairness", run["fairness"]]
            if "estimator" in run:
                cfg = inst_spec.get("generate", {}).get("config")
                if not cfg:
                    raise SystemExit(f"{sid}/{rid}: a learned estimator needs a generated instance")
                args += ["--estimator", self.estimator(cfg), "--z", run.get("z", 0.5), "--reserve", run.get("reserve", 15)]
            self.t.run("run-week", *args)
        bundle = dress(read_json(out), self.demo["geo"])
        bundle["scenario"] = sid
        bundle["label"] = entry["label"]
        write_json(out, bundle)
        entry["file"] = rel
        entry["cost"] = bundle["kpis"]["cost_total"]
        entry["checker_ok"] = bundle["week_check"]["ok"]
        self.bundles[f"{sid}/{rid}"] = rel
        return entry

    # ---- scenario

    def scenario(self, sc: dict) -> dict:
        sid = sc["id"]
        print(f"\n[{sid}] {sc['title']}", flush=True)
        entry = {k: sc[k] for k in ("id", "title", "category", "summary", "story", "view") if k in sc}
        entry["order"] = sc.get("order", 99)
        entry["hidden"] = bool(sc.get("hidden", False))
        entry["focus"] = sc.get("focus", [])
        entry["compare"] = sc.get("compare", [])
        entry["runs"] = []
        done: dict[str, Path] = {}
        specs = sc.get("instances", {})
        for key, spec in specs.items():
            done[key] = self.instance(sid, key, spec, done)
        for run in sc.get("runs", []):
            key = run.get("instance", "main")
            entry["runs"].append(self.run(sid, run, done.get(key, Path()), specs.get(key, {})))
        if "gallery" in sc:
            out = OUT / "gallery.json"
            if self.force or not out.exists():
                self.t.run("export", "--duties", ROOT / "tests" / "fixtures" / "duties.json", "--out", out)
            entry["gallery"] = {"file": "gallery.json", **sc["gallery"]}
        if "report" in sc:
            entry["report"] = REPORTS[sc["report"]["kind"]](sc["report"])
        return entry


def report_lookahead(spec: dict) -> dict:
    rows = []
    lines = (ROOT / spec["csv"]).read_text(encoding="utf-8").splitlines()
    head = lines[0].split(",")
    by_seed: dict[str, dict] = {}
    for line in lines[1:]:
        r = dict(zip(head, line.split(",")))
        by_seed.setdefault(r["seed"], {})[r["policy"]] = float(r["cost"])
    for seed, pol in sorted(by_seed.items(), key=lambda kv: int(kv[0])):
        rows.append({"seed": int(seed), **{k: pol.get(k) for k in ("myopic", "LA2", "clairvoyant")}})
    return {"kind": "lookahead", "source": spec["csv"], "rows": rows}


REPORTS = {"lookahead": report_lookahead}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bin", help="directory of the legalvrp-* executables (default: build/<preset>/apps)")
    ap.add_argument("--only", nargs="*", help="scenario ids to build (others kept from the last build)")
    ap.add_argument("--force", action="store_true", help="regenerate instances, estimators and the gallery")
    args = ap.parse_args()

    tools = Tools(find_bin(args.bin))
    demo = tomllib.loads((SCENARIOS / "demo.toml").read_text(encoding="utf-8"))
    print(f"tools: {tools.bin}  (Gurobi: {'yes' if tools.gurobi else 'no'})")
    scenarios = []
    for f in sorted(SCENARIOS.glob("*.toml")):
        if f.name == "demo.toml":
            continue
        sc = tomllib.loads(f.read_text(encoding="utf-8"))
        sc.setdefault("id", f.stem.split("-", 1)[-1])
        scenarios.append(sc)
    scenarios.sort(key=lambda s: s.get("order", 99))

    old = {}
    if (OUT / "index.json").exists():
        old = {s["id"]: s for s in read_json(OUT / "index.json").get("scenarios", [])}
    b = Builder(tools, args.force, demo)
    entries = []
    t0 = time.perf_counter()
    for sc in scenarios:
        wanted = not args.only or sc["id"] in args.only
        refs = {r["ref"].split("/")[0] for r in sc.get("runs", []) if "ref" in r}
        if not wanted and sc["id"] in old and not refs & set(args.only or []):
            entries.append(old[sc["id"]])
            for r in old[sc["id"]].get("runs", []):
                if "file" in r:
                    b.bundles[f"{sc['id']}/{r['id']}"] = r["file"]
            continue
        entries.append(b.scenario(sc))
    index = {
        "schema": 1,
        "title": demo.get("title", "legalvrp"),
        "subtitle": demo.get("subtitle", ""),
        "disclaimer": demo.get("disclaimer", ""),
        "geo": demo["geo"],
        "client": demo.get("client", {}),
        "built": dt.datetime.now().isoformat(timespec="seconds"),
        "host": platform.node(),
        "gurobi": tools.gurobi,
        "scenarios": entries,
    }
    write_json(OUT / "index.json", index, indent=2)
    print(f"\nwritten {OUT / 'index.json'}: {len(entries)} scenarios in {time.perf_counter() - t0:.0f} s")


if __name__ == "__main__":
    main()
