def stable_index(key: str, n: int) -> int:
    return int(hashlib.sha256(key.encode("utf-8")).hexdigest()[:8], 16) % n


def customer_display_name(c: dict, salt: str, used: set[str]) -> str:
    if not c.get("name", "").startswith(("site ", "grocery ", "restaurant ")):
        return c["name"]  # hand-built or real data: keep
    for attempt in range(50):
        k = f"{salt}/{c['id']}/{attempt}"
        if c["type"] == "grocery":
            name = f"{GROCERY[stable_index(k + 'g', len(GROCERY))]} {NAMES[stable_index(k, len(NAMES))]}"
        elif c["type"] == "restaurant":
            name = f"{RESTAURANT[stable_index(k + 'r', len(RESTAURANT))]} {NAMES[stable_index(k, len(NAMES))]}"
        else:
            name = f"{SITE[stable_index(k + 's', len(SITE))]} {SITE_PLACES[stable_index(k, len(SITE_PLACES))]}"
        if name not in used:
            used.add(name)
            return name
    return c["name"]


def dress(bundle: dict, geo: dict) -> dict:
    inst = bundle["instance"]
    lat0, lon0 = geo["lat"], geo["lon"]
    kx = 111.320 * math.cos(math.radians(lat0))

    def place(obj: dict) -> None:
        if obj.get("lat") is None or obj.get("lon") is None:  # real coordinates (import path) are kept
            obj["lat"] = round(lat0 + obj["y_km"] / 110.574, 6)
            obj["lon"] = round(lon0 + obj["x_km"] / kx, 6)
            obj["geo_synthetic"] = True

    place(inst["depot"])
    inst["depot"]["name"] = geo.get("depot_name", "Dépôt")
    salt = f"{inst['name']}/{inst['seed']}"
    used: set[str] = set()
    for c in inst["customers"]:
        place(c)
        c["display_name"] = customer_display_name(c, salt, used)
    for i, d in enumerate(inst["drivers"]):
        d["display_name"] = DRIVERS[i % len(DRIVERS)]
    bundle["geo"] = {"anchor": geo, "synthetic": any(c.get("geo_synthetic") for c in inst["customers"])}
    return bundle


