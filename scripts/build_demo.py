# ---------------------------------------------------------------- hand-built instances (school cases)
#
# Each builder returns (week, matrix) dictionaries in the schema of docs/DATA.md. Rules, contracts
# and costs are copied from a generated instance (`base`), so the cases obey config/*.yaml.


def hand_week(base: dict, name: str, driver: tuple[int, int], customers: list[dict], orders: list[dict]) -> dict:
    return {
        "attempt": 0, "certified": False, "contracts": base["contracts"], "costs": base["costs"],
        "customers": customers, "days": 1, "depot": {"id": "depot", "x_km": 0.0, "y_km": 0.0},
        "drivers": [{"available_days": [0], "contract_class": "full_time", "id": "k1",
                     "shift_start": driver[0], "shift_end_max": driver[1], "truck_id": "t1"}],
        "name": name, "orders": orders, "rules": dict(base["rules"]), "seed": 0,
        "trucks": [{"capacity_pallets": 18, "has_tail_lift": False, "id": "t1"}],
    }


def customer(cid: str, name: str, x: float, y: float, window: tuple[int, int], ctype="site") -> dict:
    return {"id": cid, "name": name, "type": ctype, "x_km": x, "y_km": y,
            "window_start": window[0], "window_end": window[1], "needs_tail_lift": False}


def order(cid: str, service: int, pallets=2, penalty=1000.0) -> dict:
    return {"id": f"o-{cid}", "customer_id": cid, "day": 0, "pallets": pallets, "postpone_penalty": penalty,
            "service_mu": service, "service_sigma": 0}


def matrix(ids: list[str], minutes: list[list[int]], kmh=55.0) -> dict:
    return {"node_ids": ids, "time_min": minutes,
            "dist_km": [[round(t * kmh / 60.0, 3) for t in row] for row in minutes]}


def closure(n: int, arcs: dict[tuple[int, int], int]) -> list[list[int]]:
    """Shortest travel times over the given symmetric arcs (Floyd-Warshall): a metric matrix."""
    inf = 10**6
    d = [[0 if i == j else inf for j in range(n)] for i in range(n)]
    for (i, j), t in arcs.items():
        d[i][j] = d[j][i] = min(d[i][j], t)
    for k in range(n):
        for i in range(n):
            for j in range(n):
                d[i][j] = min(d[i][j], d[i][k] + d[k][j])
    return d


def build_trap_drive(base: dict):
    # Trap (a) of the specification (T6, D-032): legs depot-A 60, A-B 140, B-C 200, C-depot 140 min.
    # No single break position splits the 540 min of driving into two blocks <= 270.
    cs = [customer("A", "Client A", 55.0, 0.0, (360, 1100)),
          customer("B", "Client B", 150.0, 85.0, (360, 1100)),
          customer("C", "Client C", -20.0, 125.0, (360, 1100))]
    w = hand_week(base, "piege_conduite", (360, 1125), cs, [order(c["id"], 10) for c in cs])
    m = matrix(["depot", "A", "B", "C"], closure(4, {(0, 1): 60, (1, 2): 140, (2, 3): 200, (3, 0): 140}))
    return w, m


def build_split_window(base: dict):
    # V1-T8 (test_route_eval / test_milp): A 200 min of work; B must start in [650, 660]; C opens at 800.
    # A 45-min break after A makes B late; after B, 390 min of work come before it. 15 + 30 works.
    cs = [customer("A", "Chantier A", 12.0, 18.0, (360, 1100)),
          customer("B", "Client B (créneau 10:50-11:00)", 26.0, 4.0, (650, 660), "grocery"),
          customer("C", "Chantier C", 8.0, -20.0, (800, 1100))]
    os_ = [order("A", 200), order("B", 100), order("C", 100)]
    w = hand_week(base, "pause_fractionnee", (360, 1125), cs, os_)
    m = matrix(["depot", "A", "B", "C"], [[0, 30, 30, 30], [30, 0, 30, 30], [30, 30, 0, 30], [30, 30, 30, 0]])
    return w, m


def build_short_break(base: dict):
    # V1-T8: 540 min of work in a shift ending at 15:35: only a 30-min break fits before the end.
    cs = [customer("A", "Chantier A", 15.0, 20.0, (360, 1100)),
          customer("B", "Chantier B", 25.0, -6.0, (360, 1100))]
    os_ = [order("A", 300), order("B", 120)]
    w = hand_week(base, "pause_courte", (360, 935), cs, os_)
    m = matrix(["depot", "A", "B"], [[0, 30, 30], [30, 0, 30], [30, 30, 0]])
    return w, m


HAND_INSTANCES = {"trap_drive": build_trap_drive, "split_window": build_split_window, "short_break": build_short_break}


def hand_plan(week: dict, mat: dict, sequence: list[str], breaks: list[tuple[str, int]]) -> dict:
    """A consistent one-day plan: leave at shift start + prep, serve on arrival (or at the window
    opening), breaks right after the given services. Legality is the checker's business."""
    rules = week["rules"]
    drv = week["drivers"][0]
    ids = mat["node_ids"]
    by_id = {o["id"]: o for o in week["orders"]}
    cust = {c["id"]: c for c in week["customers"]}
    t = drv["shift_start"] + rules["depot_prep"]
    route = {"driver_id": drv["id"], "order_ids": sequence, "departure": t, "arrivals": [], "service_starts": [],
             "breaks": [{"after": o, "minutes": m} for o, m in breaks]}
    here = 0
    for oid in sequence:
        o = by_id[oid]
        there = ids.index(o["customer_id"])
        t += mat["time_min"][here][there]
        route["arrivals"].append(t)
        start = max(t, cust[o["customer_id"]]["window_start"])
        route["service_starts"].append(start)
        t = start + o["service_mu"] + sum(m for b, m in breaks if b == oid)
        here = there
    route["return_time"] = t + mat["time_min"][here][0]
    served = set(sequence)
    return {"day": 0, "objective": 0.0, "routes": [route], "solver_stats": SOLVER_STATS_HAND,
            "postponed_order_ids": [o["id"] for o in week["orders"] if o["id"] not in served]}


