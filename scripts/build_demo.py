# ---------------------------------------------------------------- tools


class Tools:
    def __init__(self, bin_dir: Path):
        self.bin = bin_dir
        self.gurobi = (bin_dir / f"legalvrp-bench{EXE}").exists()

    def path(self, name: str) -> Path:
        p = self.bin / f"legalvrp-{name}{EXE}"
        if not p.exists():
            raise SystemExit(f"missing tool {p} (build the project first, see docs/APP.md)")
        return p

    def run(self, name: str, *args: object, ok=(0,)) -> int:
        cmd = [str(self.path(name)), *map(str, args)]
        print("  $", " ".join(Path(cmd[0]).name if i == 0 else c for i, c in enumerate(cmd)), flush=True)
        t0 = time.perf_counter()
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, env={**os.environ, "LEGALVRP_ROOT": str(ROOT)})
        if r.returncode not in ok:
            sys.stderr.write(r.stdout + r.stderr)
            raise SystemExit(f"{name} failed with exit code {r.returncode}")
        last = [line for line in r.stdout.splitlines() if line.strip()][-1:] or [""]
        print(f"    {last[0][:110]}  ({time.perf_counter() - t0:.1f} s)", flush=True)
        return r.returncode


def find_bin(explicit: str | None) -> Path:
    if explicit:
        return Path(explicit).resolve()
    # Release builds first; a Gurobi build before a build without it.
    for preset in ("msvc-release", "release", "demo", "msvc-debug", "ci-linux"):
        d = ROOT / "build" / preset / "apps"
        if (d / f"legalvrp-run-week{EXE}").exists():
            return d
    for d in sorted((ROOT / "build").glob("*/apps")):
        if (d / f"legalvrp-run-week{EXE}").exists():
            return d
    raise SystemExit("no build found under build/*/apps: build the project first (docs/APP.md)")


# ---------------------------------------------------------------- JSON helpers


def read_json(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def write_json(p: Path, data, indent=None) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(data, ensure_ascii=False, indent=indent, sort_keys=indent is not None), encoding="utf-8", newline="\n")


