#!/usr/bin/env python3
"""Build the scenarios of the visual application (docs/APP_PLAN.md, A3).

    python scripts/build_demo.py                 # every scenario of scenarios/*.toml
    python scripts/build_demo.py --only semaine  # one scenario (and what it reuses)
    python scripts/build_demo.py --bin build/msvc-release/apps --force

Reads scenarios/*.toml, prepares the instances (generated by legalvrp-generate, or hand-built
here: the school cases of the law), runs the C++ tools (legalvrp-run-week --bundle,
legalvrp-export, legalvrp-learn), dresses the bundles for display (customer and driver names,
latitude/longitude around the anchor of scenarios/demo.toml) and writes results/demo/index.json,
the manifest the application reads.

Every number shown by the application comes from these bundles, i.e. from the checker. The
dressing only adds names and map coordinates: it never changes a time, a cost or a verdict.

Python >= 3.11, standard library only. Gurobi is used when the binaries were built with it
(runs marked requires_gurobi are skipped otherwise).
"""
